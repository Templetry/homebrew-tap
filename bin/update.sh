#!/usr/bin/env bash
# Regenerates Formula/templetry.rb from the latest engine release.
#
# The formula is generated, never hand-edited: eight hashes across four
# platforms is exactly the kind of thing a person gets wrong once and nobody
# notices until an install fails its integrity check.
set -euo pipefail

REPO="Templetry/engine"
FORMULA="Formula/templetry.rb"

tag="${1-}"
if [ -z "$tag" ]; then
  # Unauthenticated calls share one rate limit per runner IP, which is how a
  # daily job that makes one request still gets a 403. Use the token when the
  # workflow provides one.
  auth=()
  [ -n "${GITHUB_TOKEN-}" ] && auth=(-H "Authorization: Bearer $GITHUB_TOKEN")
  tag=$(curl -fsSL "${auth[@]}" "https://api.github.com/repos/$REPO/releases/latest" \
    | sed -n 's/.*"tag_name": *"\([^"]*\)".*/\1/p' | head -1)
fi
[ -n "$tag" ] || { echo "::error::could not determine the latest release"; exit 1; }
version="${tag#v}"

current=""
[ -f "$FORMULA" ] && current=$(grep -o "download/v[0-9][^/]*" "$FORMULA" | head -1 | cut -c11-)
if [ "$current" = "$version" ]; then
  echo "already at $version"
  exit 0
fi
echo "${current:-none} -> $version"

sums=$(curl -fsSL "https://github.com/$REPO/releases/download/$tag/SHA256SUMS")

hash_of() {
  local h
  h=$(printf '%s\n' "$sums" | awk -v a="$1" '$2 == a { print $1 }')
  # An empty hash would produce a formula that fails every install with an
  # integrity error, which reads like corruption rather than like a bad build.
  [ -n "$h" ] || { echo "::error::$1 is not listed in SHA256SUMS for $tag" >&2; exit 1; }
  printf '%s' "$h"
}

base="https://github.com/$REPO/releases/download/$tag"

mkdir -p Formula
cat > "$FORMULA" <<FORMULA_END
# Generated by bin/update.sh from the engine's published release. Do not edit
# by hand: run the script, or let the daily workflow do it.
class Templetry < Formula
  desc "Project scaffolding for every platform, delivered to any forge (CLI + MCP server)"
  homepage "https://github.com/Templetry"
  license "Apache-2.0"

  on_macos do
    on_arm do
      url "$base/templetry-darwin-arm64"
      sha256 "$(hash_of templetry-darwin-arm64)"

      resource "mcp" do
        url "$base/templetry-mcp-darwin-arm64"
        sha256 "$(hash_of templetry-mcp-darwin-arm64)"
      end
    end

    on_intel do
      url "$base/templetry-darwin-amd64"
      sha256 "$(hash_of templetry-darwin-amd64)"

      resource "mcp" do
        url "$base/templetry-mcp-darwin-amd64"
        sha256 "$(hash_of templetry-mcp-darwin-amd64)"
      end
    end
  end

  on_linux do
    on_arm do
      url "$base/templetry-linux-arm64"
      sha256 "$(hash_of templetry-linux-arm64)"

      resource "mcp" do
        url "$base/templetry-mcp-linux-arm64"
        sha256 "$(hash_of templetry-mcp-linux-arm64)"
      end
    end

    on_intel do
      url "$base/templetry-linux-amd64"
      sha256 "$(hash_of templetry-linux-amd64)"

      resource "mcp" do
        url "$base/templetry-mcp-linux-amd64"
        sha256 "$(hash_of templetry-mcp-linux-amd64)"
      end
    end
  end

  def install
    # The release assets are bare binaries, so each arrives named after itself.
    bin.install Dir["templetry-*"].reject { |f| f.include?("-mcp-") }.first => "templetry"

    resource("mcp").stage do
      bin.install Dir["templetry-mcp-*"].first => "templetry-mcp"
    end
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/templetry version")

    # A real render, so the test proves the binary works rather than that it
    # is merely present.
    (testpath/"t/template.yml").write <<~YAML
      schema_version: 1
      name: smoke
      variables:
        - key: project_name
          type: string
      identity:
        - from: "TemplateApp"
          to: "{project_name.pascal}"
    YAML
    (testpath/"t/README.md").write "TemplateApp\n"

    system bin/"templetry", "render", "--template", testpath/"t",
           "--out", testpath/"out", "--set", "project_name=Smoke Test"
    assert_equal "SmokeTest\n", (testpath/"out/README.md").read
  end
end
FORMULA_END

echo "updated=true" >> "${GITHUB_OUTPUT:-/dev/null}"
echo "version=$version" >> "${GITHUB_OUTPUT:-/dev/null}"
echo "wrote $FORMULA at $version"
